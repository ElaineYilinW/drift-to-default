"""Exploratory re-analyses for the third internal review (not preregistered).

For one run directory of held, L*-shifted openings (files {scene}_{arm}__{ver}_s{seed}.npz, ver z0 or [mp]NN = an L*
shift of -NN / +NN; scenes rx.. = NAVSIM, gx.. = generated by the model): per arm and horizon T (10-s windows
[T-10, T) s after the 9 held frames, 16 fps), the within-scene least-squares slope alpha of the end L* on the opening L*
over the scene's versions (seed-mean of the per-seed slopes), and the zero-drift level mu = b0 / (1 - alpha) of the
same fit. Reports alpha by opening source (NAVSIM, generated, all) with scene-bootstrap 95% CIs and the difference
NAVSIM - generated, and the median mu over scenes per horizon. With motion arrays in the npz (generators that record
them), also the mean frame-to-frame grey change over [T-10, T) per arm.
usage: python review3_analyses.py RUN_DIR OUT.json [T ...]
"""
import glob
import json
import os
import re
import sys

import numpy as np

src, out = sys.argv[1], sys.argv[2]
TS = [int(t) for t in sys.argv[3:]] or [10, 20, 30, 40, 50, 60]
FPS, HOLD = 16, 9
rng = np.random.default_rng(0)
pat = re.compile(r"^(?P<scene>[a-z]{2}\d\d)_(?P<arm>.+?)__(?P<ver>z0|[mp]\d\d)_s(?P<seed>\d+)\.npz$")
X, M = {}, {}
for p in glob.glob(f"{src}/*.npz"):
    m = pat.match(os.path.basename(p))
    if not m:
        continue
    d = np.load(p)
    if "lab_mean" not in d.files:
        continue
    dl = 0.0 if m["ver"] == "z0" else (1 if m["ver"][0] == "p" else -1) * float(m["ver"][1:])
    key = (m["arm"], m["scene"], int(m["seed"]))
    X.setdefault(key, {})[dl] = d["lab_mean"][:, 0]
    if "motion" in d.files:
        M.setdefault(m["arm"], []).append(d["motion"])


def fit(vs, T):
    o, e = [], []
    for x in vs.values():
        if len(x) < HOLD + T * FPS:
            return None
        o.append(x[1:9].mean())
        e.append(x[HOLD + (T - 10) * FPS:HOLD + T * FPS].mean())
    o, e = np.array(o), np.array(e)
    if len(o) < 2 or o.max() - o.min() < 4:
        return None
    a, b0 = np.polyfit(o, e, 1)
    return a, b0 / (1 - a) if abs(1 - a) > 1e-6 else np.nan


def ci(v):
    v = np.asarray(v, float)
    return [float(x) for x in np.percentile([rng.choice(v, len(v)).mean() for _ in range(10000)], [2.5, 97.5])]


res = {}
for arm in sorted({k[0] for k in X}):
    r = {}
    for T in TS:
        per = {}
        for (a, sc, sd), vs in X.items():
            if a != arm:
                continue
            f = fit(vs, T)
            if f is not None:
                per.setdefault(sc, []).append(f)
        if not per:
            continue
        al = {sc: float(np.mean([f[0] for f in v])) for sc, v in per.items()}
        mu = {sc: float(np.mean([f[1] for f in v])) for sc, v in per.items()}
        g = {"navsim": [al[s] for s in al if s.startswith("rx")], "generated": [al[s] for s in al if s.startswith("gx")],
             "all": list(al.values())}
        row = {k: dict(mean=float(np.mean(v)), ci=ci(v), n=len(v)) for k, v in g.items() if len(v) >= 3}
        if len(g["navsim"]) >= 3 and len(g["generated"]) >= 3:
            dd = [rng.choice(g["navsim"], len(g["navsim"])).mean() - rng.choice(g["generated"], len(g["generated"])).mean()
                  for _ in range(10000)]
            row["navsim_minus_generated"] = dict(est=float(np.mean(g["navsim"]) - np.mean(g["generated"])),
                                                 ci=[float(x) for x in np.percentile(dd, [2.5, 97.5])])
        row["mu_median"] = float(np.nanmedian(list(mu.values())))
        if arm in M:
            row["motion"] = float(np.mean([m[HOLD + (T - 10) * FPS:HOLD + T * FPS].mean() for m in M[arm]
                                           if len(m) >= HOLD + T * FPS]))
        r[T] = row
    res[arm] = r
    for T, row in r.items():
        s = " ".join(f"{k} {v['mean']:+.2f}" for k, v in row.items() if isinstance(v, dict) and "mean" in v)
        dd = row.get("navsim_minus_generated")
        print(f"{arm:14s} T={T:3d} {s} " + (f"diff {dd['est']:+.2f} [{dd['ci'][0]:+.2f},{dd['ci'][1]:+.2f}] " if dd else "")
              + f"mu {row['mu_median']:.1f}" + (f" motion {row['motion']:.2f}" if "motion" in row else ""))
json.dump(res, open(out, "w"), indent=1)

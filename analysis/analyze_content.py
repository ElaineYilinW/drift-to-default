"""Content relaxation (preregistered, docs/preregistration_content_cn.md).

24 openings (6 scene classes x 4) generated by Self Forcing DMD, each continued under the generic city prompt (arm mis)
and under its own class prompt (arm mat) by 8 configurations; fresh starts of the generic prompt (8 seeds) give each
configuration's default. Files {opening}_{arm}_{cfg}_s0.clip.npz and fresh_{cfg}_s{seed}.clip.npz (clip_probe.py).
Class score of a frame: z = scale * (cos(frame, label_cls) - cos(frame, label_city)), the CLIP log-odds of the opening's
class against the city label. s(T) = mean z over frames in seconds [T-5, T) after the held opening (frame f -> (f-9)/16 s);
s_open = mean z over frames 1..8; mu(T) = mean over fresh seeds of the same window score for that class.
Content persistence of one video: kappa = (s(T) - mu(T)) / (s_open - mu(T)); openings with s_open - mu < 2 are excluded
from kappa analyses. A configuration's kappa is the mean over openings.
Primary (Holm over 3; supported if Holm p < .05 and the estimate > 0; two-sided one-sample t-tests over openings):
  H1 prompt sets the content default: s_mat - s_mis > 0 at T = 30 s on sf60_s3.
  H2 the sink keeps content (LongLive): kappa(ll_s3, mis) - kappa(ll_s0, mis) > 0 at T = 30 s.
  H3 the sink keeps content (Self Forcing): kappa(sf60_s3, mis) - kappa(sf60_s0, mis) > 0 at T = 60 s.
Secondary: kappa per configuration and arm at 10/20/30 s (and 40/50/60 s for sf60_*); Spearman correlation across the
8 configurations between kappa(mis, 30 s) and brightness persistence alpha_L at 31 s (preregistration 06); H1 on
tone-normalised embeddings; s_mat - s_mis for every configuration; per-class kappa; top-1 accuracy of the opening's class
among the 7 labels. 95% CIs: 10,000 bootstrap draws resampling openings within class and fresh seeds.
usage: python analyze_content.py CLIP_DIR TEXT_NPZ RELAX_RESULTS_JSON OUT_DIR
"""
import glob
import json
import os
import re
import sys

import numpy as np
from scipy import stats

src, text_npz, relax_json, out = sys.argv[1:5]
os.makedirs(out, exist_ok=True)
rng = np.random.default_rng(0)
TX = np.load(text_npz)
LAB, TEXT, SCALE = [str(x) for x in TX["labels"]], TX["text"].astype(np.float32), float(TX["scale"])
CFG = ["sf60_s3", "sf60_s0", "ll_s3", "ll_s0", "cv_s3", "gan_s3", "sid_s3", "rf"]
ALPHA_CFG = {"sf60_s3": "sf_s3", "sf60_s0": "sf_s0"}
HOR = {c: (10, 20, 30, 40, 50, 60) if c.startswith("sf60") else (10, 20, 30) for c in CFG}
pat = re.compile(r"^ct([a-z]+)(\d)_(mis|mat)_(\w+)_s0\.clip\.npz$")
fpat = re.compile(r"^fresh_(\w+)_s(\d+)\.clip\.npz$")


def scores(npz, key="emb"):
    e = npz[key].astype(np.float32)
    return npz["idx"], SCALE * (e @ TEXT.T)                     # (n,), (n, 7) scaled cosines


def window(idx, z, T):
    m = (idx >= 9 + 16 * (T - 5)) & (idx < 9 + 16 * T)
    return z[m].mean(0) if m.any() else None


V, F = {}, {}     # V[cfg][arm][opening] = dict(cls, open, win{T}, top1{T}), F[cfg][seed] = {T: (7,)}
for p in sorted(glob.glob(f"{src}/*.clip.npz")):
    b, d = os.path.basename(p), np.load(p)
    m, fm = pat.match(b), fpat.match(b)
    if m:
        cls, k, arm, cfg = m[1], m[2], m[3], m[4]
        rec = dict(cls=cls)
        for key in ("emb", "emb_tn"):
            if key not in d:
                continue
            idx, z = scores(d, key)
            ci, cc = LAB.index(cls), LAB.index("city")
            lo = z[:, ci] - z[:, cc]
            rec[key] = dict(open=float(lo[(idx >= 1) & (idx < 9)].mean()),
                            win={T: (None if window(idx, lo[:, None], T) is None else float(window(idx, lo[:, None], T)[0]))
                                 for T in range(5, 61)},
                            top1={T: float(np.mean(z[(idx >= 9 + 16 * (T - 5)) & (idx < 9 + 16 * T)].argmax(1) == ci))
                                  if ((idx >= 9 + 16 * (T - 5)) & (idx < 9 + 16 * T)).any() else None for T in (10, 20, 30, 60)})
        V.setdefault(cfg, {}).setdefault(arm, {})[f"{cls}{k}"] = rec
    elif fm:
        idx, z = scores(d)
        F.setdefault(fm[1], {})[int(fm[2])] = {T: window(idx, z, T) for T in range(5, 61)}


def mu(cfg, cls, T, seeds):
    ci, cc = LAB.index(cls), LAB.index("city")
    v = [F[cfg][s][T][ci] - F[cfg][s][T][cc] for s in seeds if F[cfg][s].get(T) is not None]
    return float(np.mean(v)) if v else None


def kappas(cfg, arm, T, openings=None, seeds=None, key="emb"):
    seeds = sorted(F.get(cfg, {})) if seeds is None else seeds
    out_ = {}
    for o, r in V.get(cfg, {}).get(arm, {}).items():
        if openings is not None and o not in openings or key not in r or r[key]["win"].get(T) is None:
            continue
        m_ = mu(cfg, r["cls"], T, seeds)
        if m_ is None or r[key]["open"] - m_ < 2:
            continue
        out_[o] = (r[key]["win"][T] - m_) / (r[key]["open"] - m_)
    return out_


CLASSES = sorted({r["cls"] for c in V.values() for a in c.values() for r in a.values()})
ALL_O = sorted({o for c in V.values() for a in c.values() for o in a})


def boot(fn, n=10000):
    """fn(openings_list, seeds_by_cfg) -> float or None; resample openings within class and fresh seeds."""
    by_cls = {c: [o for o in ALL_O if o.startswith(c)] for c in CLASSES}
    vals = []
    for _ in range(n):
        ops = [o for c in CLASSES for o in rng.choice(by_cls[c], len(by_cls[c]))]
        sd = {c: list(rng.choice(sorted(F[c]), len(F[c]))) for c in F}
        v = fn(ops, sd)
        if v is not None and np.isfinite(v):
            vals.append(v)
    return np.percentile(vals, [2.5, 97.5]).tolist() if vals else None


def mean_over(ops, d):
    v = [d[o] for o in ops if o in d]
    return float(np.mean(v)) if v else None


res = {"counts": {c: {a: len(v) for a, v in V[c].items()} for c in V}, "fresh_counts": {c: len(v) for c, v in F.items()},
       "kappa": {}, "prompt_effect": {}, "top1": {}, "per_class": {}}
# secondary: kappa per configuration x arm x horizon (bootstrap CIs at 30 / 60 s only, curves without CIs)
for c in CFG:
    if c not in V:
        continue
    res["kappa"][c] = {}
    for arm in ("mis", "mat"):
        res["kappa"][c][arm] = {}
        for T in range(5, 61):
            k = kappas(c, arm, T)
            if not k:
                continue
            e = dict(mean=float(np.mean(list(k.values()))), n=len(k))
            if T in (30, 60):
                e["ci"] = boot(lambda ops, sd, c=c, arm=arm, T=T: mean_over(ops, kappas(c, arm, T, set(ops), sd.get(c))), 2000)
            res["kappa"][c][arm][T] = e
        res["top1"].setdefault(c, {})[arm] = {T: float(np.mean([r["emb"]["top1"][T] for r in V[c].get(arm, {}).values()
                                                               if r["emb"]["top1"].get(T) is not None]))
                                              for T in (10, 20, 30, 60) if any(r["emb"]["top1"].get(T) is not None
                                                                                for r in V[c].get(arm, {}).values())}
    for T in HOR[c]:
        a, b = V[c].get("mat", {}), V[c].get("mis", {})
        d = {o: a[o]["emb"]["win"][T] - b[o]["emb"]["win"][T] for o in a if o in b and a[o]["emb"]["win"].get(T) is not None
             and b[o]["emb"]["win"].get(T) is not None}
        if d:
            res["prompt_effect"].setdefault(c, {})[T] = dict(est=float(np.mean(list(d.values()))), n=len(d),
                                                             ci=boot(lambda ops, sd, d=d: mean_over(ops, d), 2000))
    for cls in CLASSES:
        k = kappas(c, "mis", 30, {o for o in ALL_O if o.startswith(cls)})
        if k:
            res["per_class"].setdefault(c, {})[cls] = float(np.mean(list(k.values())))


def kdiff(ops, sd, x, y, T):
    kx, ky = kappas(x, "mis", T, set(ops), sd.get(x)), kappas(y, "mis", T, set(ops), sd.get(y))
    return mean_over(ops, {o: kx[o] - ky[o] for o in kx if o in ky})


def paired(d):
    v = np.array(list(d.values()))
    return dict(est=float(v.mean()), ci=boot(lambda ops, sd: mean_over(ops, d)), p=float(stats.ttest_1samp(v, 0).pvalue),
                n=int(len(v)))


tests = {}
a, b = V.get("sf60_s3", {}).get("mat", {}), V.get("sf60_s3", {}).get("mis", {})
tests["H1"] = paired({o: a[o]["emb"]["win"][30] - b[o]["emb"]["win"][30] for o in a if o in b})
for h, (x, y, T) in {"H2": ("ll_s3", "ll_s0", 30), "H3": ("sf60_s3", "sf60_s0", 60)}.items():
    kx, ky = kappas(x, "mis", T), kappas(y, "mis", T)
    d = {o: kx[o] - ky[o] for o in kx if o in ky}
    t = paired(d)
    t["ci"] = boot(lambda ops, sd, x=x, y=y, T=T: kdiff(ops, sd, x, y, T))
    t.update(mean_x=float(np.mean([kx[o] for o in d])), mean_y=float(np.mean([ky[o] for o in d])))
    tests[h] = t
running = 0.0
for i, k in enumerate(sorted(tests, key=lambda k: tests[k]["p"])):
    running = max(running, min(1.0, (len(tests) - i) * tests[k]["p"]))
    tests[k]["p_holm"] = running
    tests[k]["supported"] = bool(running < 0.05 and tests[k]["est"] > 0)
res["primary"] = tests
# secondary: H1 on tone-normalised embeddings
a, b = V.get("sf60_s3", {}).get("mat", {}), V.get("sf60_s3", {}).get("mis", {})
dtn = {o: a[o]["emb_tn"]["win"][30] - b[o]["emb_tn"]["win"][30] for o in a if o in b and "emb_tn" in a[o] and "emb_tn" in b[o]}
res["H1_tone_normalised"] = paired(dtn) if dtn else None
for c in CFG:
    if c in V and "mis" in V[c]:
        k = kappas(c, "mis", 30, key="emb_tn")
        if k:
            res.setdefault("kappa_tone_normalised_30s", {})[c] = float(np.mean(list(k.values())))
# secondary: content persistence vs brightness persistence across configurations
rel = json.load(open(relax_json))["per_cfg"]
pairs = [(res["kappa"][c]["mis"][30]["mean"], rel[ALPHA_CFG.get(c, c)]["alpha_L"]["mean"]) for c in CFG
         if c in res["kappa"] and 30 in res["kappa"][c].get("mis", {}) and ALPHA_CFG.get(c, c) in rel]
if len(pairs) >= 4:
    r_, p_ = stats.spearmanr(*zip(*pairs))
    res["spearman_kappa_alphaL"] = dict(rho=float(r_), p=float(p_), n=len(pairs))
json.dump(res, open(f"{out}/content_results.json", "w"), indent=1)
print(json.dumps(res["primary"], indent=1))
print({c: {arm: round(v[30]["mean"], 3) for arm, v in r.items() if 30 in v} for c, r in res["kappa"].items()})
print(res.get("spearman_kappa_alphaL"), res.get("H1_tone_normalised"))

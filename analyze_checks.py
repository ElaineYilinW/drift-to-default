"""Validity checks for the drift mechanism (ctx_swap2.py runs) and the real-opening result (self-opening control).

C1 natural swap: does the next chunk follow a NATURALLY different window (another seed's window at the same
   positions) as much as a synthetic tone shift? slope of dL_k on dL_win through the origin, prompt bootstrap.
C2 dose: window slopes by |dose| (2, 5, 10 L) to test linearity; anchor-only slope; joint (anchor + window) shift
   = total response to shifting the whole context.
C3 attractor over time: per video and intervention time k, M = (L_k - w_win*L_win - w_sink*L_sink)/(1 - w_win - w_sink)
   with the video's own dose-estimated weights; per-video linear trend of M over time (per 10 s), prompt bootstrap CI,
   and the difference between configurations.
C4 real vs self opening: start-to-end and early (first 2 s after the opening) vs late (per-second) brightness change
   for a held real NAVSIM frame vs a held frame generated by the model itself (same generic prompt and procedure).
usage: python analyze_checks.py SWAP2_DIR REAL_DIR SELF_DIR OUT_DIR
"""
import glob
import json
import os
import re
import sys

import numpy as np
import pandas as pd

swap2, realdir, selfdir, out = sys.argv[1:5]
os.makedirs(out, exist_ok=True)
rng = np.random.default_rng(0)
SEC_PER_CHUNK = 12 / 16


def slope0(x, y):
    m = np.abs(x) > 1e-9
    return float((x[m] * y[m]).sum() / (x[m] ** 2).sum()) if m.any() else np.nan


def boot_prompt(d, fn, B=2000):
    ps = d.prompt.unique()
    vals = [fn(pd.concat([d[d.prompt == p] for p in rng.choice(ps, len(ps))])) for _ in range(B)]
    return [float(np.nanpercentile(vals, 2.5)), float(np.nanpercentile(vals, 97.5))]


res = {}
nat, dose = [], []
for f in glob.glob(f"{swap2}/*.swap2.json"):
    d = json.load(open(f))
    for r in d["rows"]:
        (nat if d["mode"] == "natural" else dose).append(dict(prompt=d["prompt_id"], tag=d["tag"], sink=d["sink"], **r))
N, D = pd.DataFrame(nat), pd.DataFrame(dose)

# C1
if len(N):
    N = N[N.A != N.B].copy()
    N["dLk"], N["dLw"] = N.L_k - N.L_k_A, N.L_winB - N.L_winA
    res["C1_natural"] = {tag: dict(n=int(len(g)), slope=slope0(g.dLw.values, g.dLk.values),
                                   ci=boot_prompt(g, lambda x: slope0(x.dLw.values, x.dLk.values)),
                                   mean_abs_dLw=float(g.dLw.abs().mean()))
                         for tag, g in N.groupby("tag")}
# C2 + C3
if len(D):
    b0 = D[(D.ds == 0) & (D.dw == 0)].set_index(["prompt", "tag", "seed", "k"])[["L_k", "L_sink", "L_win"]]
    D = D.join(b0, on=["prompt", "tag", "seed", "k"], rsuffix="0")
    D["dLk"], D["dLw"] = D.L_k - D.L_k0, D.L_win - D.L_win0
    D["dLs"] = (D.L_sink - D.L_sink0) if "L_sink" in D else 0
    res["replay_exact_dose"] = bool((D[(D.ds == 0) & (D.dw == 0)].L_k - D[(D.ds == 0) & (D.dw == 0)].L_k_uninterrupted).abs().max() < 1e-6)
    c2 = {}
    for tag, g in D.groupby("tag"):
        win = g[(g.ds == 0) & (g.dw != 0)]
        r = {f"w_win_dose{int(m)}": dict(slope=slope0(h.dLw.values, h.dLk.values),
                                          ci=boot_prompt(h, lambda x: slope0(x.dLw.values, x.dLk.values)))
             for m, h in win.groupby(win.dw.abs())}
        sk = g[(g.ds != 0) & (g.dw == 0)]
        if len(sk):
            r["w_sink_dose10"] = dict(slope=slope0(sk.dLs.values, sk.dLk.values),
                                      ci=boot_prompt(sk, lambda x: slope0(x.dLs.values, x.dLk.values)))
        jt = g[(g.ds != 0) & (g.dw != 0)]
        if len(jt):
            ctx = (jt.dLw * 18 + jt.dLs * 3) / 21          # frame-weighted shift of the whole context
            jt = jt.assign(dctx=ctx)
            r["joint_total_response"] = dict(slope=slope0(jt.dctx.values, jt.dLk.values),
                                             ci=boot_prompt(jt, lambda x: slope0(x.dctx.values, x.dLk.values)))
        c2[tag] = r
    res["C2_dose"] = c2
    # C3: per-video weights from its own dose rows, then M per k and its trend
    mrows = []
    for (p, tag, seed), g in D.groupby(["prompt", "tag", "seed"]):
        win = g[(g.ds == 0) & (g.dw != 0)]
        ww = slope0(win.dLw.values, win.dLk.values)
        sk = g[(g.ds != 0) & (g.dw == 0)]
        wsk = slope0(sk.dLs.values, sk.dLk.values) if len(sk) else 0.0
        for k, h in g[(g.ds == 0) & (g.dw == 0)].groupby("k"):
            r0 = h.iloc[0]
            Ls = r0.L_sink if r0.sink else 0.0
            mrows.append(dict(prompt=p, tag=tag, seed=seed, k=k, t=k * SEC_PER_CHUNK, w_win=ww, w_sink=wsk,
                              M=(r0.L_k - ww * r0.L_win - wsk * Ls) / (1 - ww - wsk)))
    M = pd.DataFrame(mrows)
    M.to_csv(f"{out}/attractor_by_time.csv", index=False)
    tr = M.groupby(["prompt", "tag"]).apply(lambda x: np.polyfit(x.t, x.M, 1)[0] * 10).rename("slope10").reset_index()
    c3 = {}
    for tag, g in tr.groupby("tag"):
        c3[tag] = dict(M_trend_per_10s=float(g.slope10.mean()),
                       ci=boot_prompt(g, lambda x: x.slope10.mean()),
                       M_mean_by_time=M[M.tag == tag].groupby("t").M.mean().round(2).to_dict(),
                       M_sd_across_videos=float(M[M.tag == tag].groupby("t").M.std().mean()))
    if {"w21s0", "w21s3"} <= set(tr.tag):
        w = tr.pivot(index="prompt", columns="tag", values="slope10").dropna()
        diff = w["w21s3"] - w["w21s0"]
        bs = [diff.sample(len(diff), replace=True, random_state=int(s)).mean() for s in rng.integers(0, 2**31, 2000)]
        c3["sink_minus_nosink_trend"] = dict(diff=float(diff.mean()), ci=[float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))])
    res["C3_attractor_trend"] = c3

# C4
def opening_rows(d, prefix):
    rows = []
    for p in glob.glob(f"{d}/{prefix}*_none_s*.npz"):
        m = re.match(rf"({prefix}\d+)_none_s(\d+)\.npz", os.path.basename(p))
        L = np.load(p)["lab_mean"][:, 0]
        o = L[1:9].mean()
        sec = np.arange(len(L)) / 16
        early = L[(sec >= 1) & (sec < 3)].mean() - o
        late_slope = np.polyfit(sec[sec >= 3], L[sec >= 3], 1)[0]
        rows.append(dict(scene=m[1], seed=int(m[2]), L_open=o, dL_end=L[-32:].mean() - o, early_2s=early, late_per_s=late_slope))
    return pd.DataFrame(rows)


R, S = opening_rows(realdir, "real"), opening_rows(selfdir, "self")
if len(R) and len(S):
    def summ(x):
        g = x.groupby("scene").mean(numeric_only=True)
        return dict(n_scenes=int(len(g)), L_open=float(g.L_open.mean()), dL_end=float(g.dL_end.mean()),
                    early_2s=float(g.early_2s.mean()), late_per_s=float(g.late_per_s.mean()), frac_darker=float((x.dL_end < 0).mean()))
    gR, gS = R.groupby("scene").mean(numeric_only=True), S.groupby("scene").mean(numeric_only=True)
    bs = [gR.dL_end.sample(len(gR), replace=True, random_state=int(s)).mean() - gS.dL_end.sample(len(gS), replace=True, random_state=int(s) + 1).mean()
          for s in rng.integers(0, 2**31, 2000)]
    res["C4_real_vs_self"] = dict(real=summ(R), self=summ(S), real_minus_self_dL_end=float(gR.dL_end.mean() - gS.dL_end.mean()),
                                  ci=[float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))])
json.dump(res, open(f"{out}/checks.json", "w"), indent=1, default=float)
print(json.dumps(res, indent=1, default=float))
